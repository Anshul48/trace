"""Storage boundaries used by the Trace V2 application layer.

The embedded adapter is deliberately still useful for local development and
replay drills.  This module prevents the rest of the application from making
SQLite-specific assumptions and documents the small set of capabilities a
production repository must provide.

The protocols use ``Any`` for row-shaped values because the public contracts
are dictionaries today and a PostgreSQL implementation may use dataclasses or
record mappings internally.  They are runtime-checkable only at the coarse
interface level; correctness remains enforced by the repository's transaction
and event invariants.
"""

from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Iterable, Protocol, Sequence


class Repository(Protocol):
    """Canonical and projection operations required by :class:`TraceService`.

    Implementations must make every canonical mutation and its outbox record
    part of one transaction.  Returned rows must be tenant-scoped by the
    repository, never by an untrusted caller-provided filter alone.
    """

    def transaction(self) -> AbstractContextManager[Any]: ...

    def ingest(self, **kwargs: Any) -> dict[str, Any]: ...

    def edit_node(self, **kwargs: Any) -> dict[str, Any]: ...

    def split_node(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def create_alias(self, **kwargs: Any) -> dict[str, Any]: ...

    def queryable_atoms(self, workspace_id: str | None, as_of_event: int | None = None, **kwargs: Any) -> list[dict[str, Any]]: ...

    def temporal_candidate_atoms(self, workspace_id: str | None, as_of_event: int | None = None) -> list[dict[str, Any]]: ...

    def iter_indexable_atom_versions(self, workspace_id: str | None, as_of_event: int | None = None, *, batch_size: int = 1_000) -> Iterable[dict[str, Any]]: ...

    def current_nodes(self, workspace_id: str, as_of_event: int | None = None) -> list[dict[str, Any]]: ...

    def current_edges(self, workspace_id: str, as_of_event: int | None = None) -> list[dict[str, Any]]: ...

    def atom_versions(self, atom_version_ids: Sequence[str]) -> list[dict[str, Any]]: ...

    def get_source_lifecycle(self, atom_version_id: str, *, as_of_event: int | None = None) -> dict[str, Any]: ...

    def transition_source_lifecycle(self, atom_version_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def transition_source_authorization(self, atom_version_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def resolve_source_authorization(self, atom_version_id: str, *, as_of_event: int | None = None) -> dict[str, Any]: ...

    def erase_source(self, atom_version_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def cortex_component_revisions(self, workspace_id: str, component_kinds: Sequence[str]) -> dict[str, list[str]]: ...

    def atom_versions_by_event_range(self, workspace_id: str, from_event_offset: int, through_event_offset: int, *, limit: int = 1_000) -> list[dict[str, Any]]: ...

    def hot_candidates(self, workspace_id: str, query: str, *, limit: int = 100, visibility: Sequence[str] | None = None, facets: Sequence[str] | None = None, as_of_event: int | None = None) -> list[dict[str, Any]]: ...

    def current_atom_versions_for_nodes(self, workspace_id: str, node_ids: Sequence[str], *, as_of_event: int | None = None) -> list[dict[str, Any]]: ...

    def dense_vectors(self, provider_id: str, atom_version_ids: Sequence[str]) -> dict[str, list[float]]: ...

    def upsert_dense_vectors(self, **kwargs: Any) -> int: ...

    def save_bundle(self, **kwargs: Any) -> dict[str, Any]: ...

    def get_bundle(self, bundle_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def feedback_scores(self, workspace_id: str, atom_version_ids: Sequence[str]) -> dict[str, float]: ...

    def create_job(self, **kwargs: Any) -> dict[str, Any]: ...

    def get_job(self, job_id: str) -> dict[str, Any]: ...

    def list_jobs(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def claim_jobs(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def complete_job(self, job_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def fail_job(self, job_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def cancel_job(self, job_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def retry_job(self, job_id: str, **kwargs: Any) -> dict[str, Any]: ...

    # Replaceable Cortex projection control plane. None of these operations
    # may create trusted canonical evidence edges.
    def get_cognitive_policy(self, workspace_id: str) -> dict[str, Any]: ...

    def put_cognitive_policy(self, **kwargs: Any) -> dict[str, Any]: ...

    def create_projection_run(self, **kwargs: Any) -> dict[str, Any]: ...

    def transition_projection_run(self, projection_run_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def activate_projection_run(self, projection_run_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def effective_projection_run(self, workspace_id: str, projection_kind: str, **kwargs: Any) -> dict[str, Any] | None: ...

    def projection_objects_page(self, projection_run_id: str, *, object_kind: str, after_logical_key: str | None = None, limit: int = 1_000) -> list[dict[str, Any]]: ...

    def hierarchy_frontier(self, workspace_id: str, query: str, **kwargs: Any) -> list[dict[str, Any]]: ...

    def hierarchy_objects(self, workspace_id: str, projection_object_ids: Sequence[str], **kwargs: Any) -> list[dict[str, Any]]: ...

    def hierarchy_children(self, workspace_id: str, parent_projection_object_ids: Sequence[str], **kwargs: Any) -> list[dict[str, Any]]: ...

    def affinity_neighbors(self, workspace_id: str, atom_version_ids: Sequence[str], **kwargs: Any) -> list[dict[str, Any]]: ...

    def activation_priors(self, workspace_id: str, atom_version_ids: Sequence[str], **kwargs: Any) -> dict[str, list[dict[str, Any]]]: ...

    # Unified Cortex Release Lifecycle
    def create_cortex_release(self, **kwargs: Any) -> dict[str, Any]: ...

    def get_cortex_release(self, release_id: str) -> dict[str, Any]: ...

    def get_active_cortex_release(self, workspace_id: str) -> dict[str, Any] | None: ...

    def get_cortex_release_as_of_event(self, workspace_id: str, as_of_event: int) -> dict[str, Any] | None: ...

    def list_cortex_releases(self, workspace_id: str, status: str | None = None, limit: int = 50) -> list[dict[str, Any]]: ...

    def record_cortex_component(self, release_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def validate_cortex_release(self, release_id: str, validation_receipt: dict[str, Any]) -> dict[str, Any]: ...

    def activate_cortex_release(self, release_id: str, **kwargs: Any) -> dict[str, Any]: ...

    def rollback_cortex_release(self, workspace_id: str, target_release_id: str | None = None, **kwargs: Any) -> dict[str, Any]: ...

    def fail_cortex_release(self, release_id: str, failure_detail: str) -> dict[str, Any]: ...



class AttachmentStore(Protocol):
    """Private object storage for original and normalized ingress artifacts."""

    def put_bytes(self, raw: bytes, media_type: str, **kwargs: Any) -> dict[str, Any]: ...

    def put_text(self, text: str, media_type: str, **kwargs: Any) -> dict[str, Any]: ...


class LexicalIndex(Protocol):
    """Workspace-filtered lexical candidate provider."""

    provider_id: str

    def search(
        self,
        *,
        workspace_id: str,
        query: str,
        limit: int,
        visibility: Sequence[str] | None = None,
        facets: Sequence[str] | None = None,
        as_of_event: int | None = None,
        index_revision: str | None = None,
    ) -> list[dict[str, Any]]: ...

    def upsert(self, documents: Iterable[dict[str, Any]], *, revision: str) -> int: ...


class DenseIndex(Protocol):
    """Workspace-filtered dense candidate provider."""

    provider_id: str

    def search(
        self,
        *,
        workspace_id: str,
        vector: Sequence[float],
        limit: int,
        visibility: Sequence[str] | None = None,
        facets: Sequence[str] | None = None,
        as_of_event: int | None = None,
        index_revision: str | None = None,
    ) -> list[dict[str, Any]]: ...

    def upsert(self, vectors: Iterable[dict[str, Any]], *, revision: str) -> int: ...


class EventPublisher(Protocol):
    """Durable outbox publisher (NATS JetStream in production)."""

    async def publish(self, topic: str, message: dict[str, Any]) -> None: ...


class CoordinationStore(Protocol):
    """TTL coordination/cache boundary (Redis in production)."""

    def get(self, key: str) -> str | None: ...

    def set(self, key: str, value: str, *, ttl_seconds: int) -> None: ...

    def delete(self, key: str) -> None: ...
